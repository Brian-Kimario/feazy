interface FaqEntry {
  question: string;
  answer: string;
}

/** FAQPage structured data. Pass the same entries the page renders so markup and content never drift. */
export function FAQPageSchema({ faqs }: { faqs: readonly FaqEntry[] }) {
  const schema = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: faqs.map((faq) => ({
      '@type': 'Question',
      name: faq.question,
      acceptedAnswer: { '@type': 'Answer', text: faq.answer },
    })),
  };

  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{ __html: JSON.stringify(schema).replace(/</g, '\\u003c') }}
    />
  );
}
